"""Generate Python-compatible full casefold mappings; never use device locale/Unicode tables."""
import pathlib
import unicodedata

assert unicodedata.unidata_version == "16.0.0", "Use recorded Python Unicode16 toolchain"
rows=[]
for code in range(0x110000):
    char=chr(code)
    if char.casefold()!=char:
        rows.append(f'{code:x}:'+','.join(f'{ord(c):x}' for c in char.casefold()))
chunks=[';'.join(rows[i:i+20]) for i in range(0,len(rows),20)]
table=' +\n'.join('        "'+chunk+(';' if i<len(chunks)-1 else '')+'"' for i,chunk in enumerate(chunks))
source='''package org.kiosk.harness.packagecore;

import java.util.HashMap;
import java.util.Map;

/** Generated by tools/generate-package-casefold.py, Python Unicode16.0.0 full casefold. */
final class PackageCaseFold {
    private static final String DATA =
TABLE;
    private static final Map<Integer,String> MAP = new HashMap<>();
    static {
        for(String row:DATA.split(";")) {
            String[] pair=row.split(":");
            StringBuilder value=new StringBuilder();
            for(String code:pair[1].split(","))value.appendCodePoint(Integer.parseInt(code,16));
            MAP.put(Integer.parseInt(pair[0],16),value.toString());
        }
    }
    static String fold(String text) {
        StringBuilder result=new StringBuilder();
        text.codePoints().forEach(code->{String value=MAP.get(code);if(value==null)result.appendCodePoint(code);else result.append(value);});
        return result.toString();
    }
}
'''.replace('TABLE',table)
path=pathlib.Path(__file__).resolve().parents[1]/'app/src/main/java/org/kiosk/harness/packagecore/PackageCaseFold.java'
path.write_text(source,encoding='utf-8')
print(unicodedata.unidata_version,len(rows),path)
